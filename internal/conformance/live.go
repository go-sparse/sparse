package conformance

import (
	"fmt"
	"strings"

	"github.com/go-sparse/sparse/internal/scipy"
)

// LiveReport holds a report-only comparison on matrices whose behaviour is
// not enforced (ill-conditioned corpus matrices converge erratically, so
// iteration counts are listed, not asserted).
type LiveReport struct {
	Notes  []string
	Solves []SolveRow
	Orders []OrderRow
}

// RunLive compares Go and the oracle matrix by matrix, skipping (with a
// note) any case that cannot be set up, such as an IC(0) breakdown or a
// singular matrix for SuperLU.
func RunLive(s *scipy.Session, matrices []Named) LiveReport {
	var rep LiveReport
	for _, m := range matrices {
		for _, c := range DefaultSolveCases([]Named{m}) {
			label := fmt.Sprintf("%s/%s/%s", m.Name, c.Case.Solver, c.Case.Precond)
			_, sp, err := build(m.A, PrecondSpec(c.Case.Precond))
			if err != nil {
				rep.Notes = append(rep.Notes, "skipped "+label+": "+err.Error())
				continue
			}
			resp, err := s.Solve(scipy.SolveRequest{Solver: c.Case.Solver, A: scipy.FromCSR(m.A), B: RHS(m.A.Rows),
				M: sp, RTol: c.Case.RTol, Restart: c.Case.Restart})
			if err != nil {
				rep.Notes = append(rep.Notes, "skipped "+label+": "+err.Error())
				continue
			}
			rows, _ := Verify([]Named{m}, []SolveFix{{SolveCase: c.Case, Sci: resp}})
			rep.Solves = append(rep.Solves, rows...)
		}
		fix, err := GenerateOrders(s, []Named{m})
		if err != nil {
			rep.Notes = append(rep.Notes, "skipped orderings of "+m.Name+": "+err.Error())
			continue
		}
		rows, _ := VerifyOrders([]Named{m}, fix)
		rep.Orders = append(rep.Orders, rows...)
	}
	return rep
}

// Document renders docs/verification.md from the committed fixture (re-run
// on the Go side) and, when live is not nil, the corpus comparison.
func Document(f *Fixture, live *LiveReport) string {
	sm, _ := Suite(SuiteSolve) // constant names that Build accepts
	om, _ := Suite(SuiteOrder)
	solves, bad1 := Verify(sm, f.Solves)
	lsqr, bad2 := VerifyLSQR(f.LSQR)
	lsmr, bad3 := VerifyLSMR(f.LSMR)
	orders, bad4 := VerifyOrders(om, f.Orders)
	var b strings.Builder
	fmt.Fprintf(&b, "# Verification against SciPy\n\nOracle: SciPy %s, NumPy %s (`uv run --with scipy==%s --with numpy==%s`), plus SuiteSparse AMD through cvxopt %s as a binary oracle (no SuiteSparse source is used).\n\n",
		f.SciPy, f.NumPy, scipy.SciPyVersion, scipy.NumPyVersion, scipy.CvxoptVersion)
	b.WriteString("Generated by `go run ./cmd/conformance`. Every row is a Go run next to the SciPy answer recorded in `internal/conformance/testdata/oracle.json`; the regression tests re-run the Go side and fail if a row leaves its bound.\n\n")
	fmt.Fprintf(&b, "Violations of the enforced bounds when this file was written: %d.\n\n", len(bad1)+len(bad2)+len(bad3)+len(bad4))
	b.WriteString("## Bounds\n\n")
	b.WriteString("- Solvers: same `info`; true residual ≤ 1.5·rtol (or ≤ 1.5× SciPy's for MINRES); iteration count within max(3, 5%) of SciPy (25% for BiCGSTAB).\n")
	b.WriteString("- LSQR / LSMR: same `istop`; iterations within 3; solution within 1e-6; residual norm within 1e-6.\n")
	fmt.Fprintf(&b, "- Orderings: RCM bandwidth ≤ %.2f× and profile ≤ %.2f× SciPy's; Cholesky fill of AMD ≤ %.2f× SuiteSparse AMD's; LU fill with our AMD ≤ %.2f× SuperLU's minimum degree; LU fill with our COLAMD ≤ %.2f× SuperLU's COLAMD.\n\n",
		OrderBounds.RCMBandwidth, OrderBounds.RCMProfile, OrderBounds.AMDChol, OrderBounds.AMDLU, OrderBounds.COLAMDLU)
	b.WriteString("## Iterative solvers (generated matrices, rtol 1e-8, GMRES restart 30)\n\n" + SolveTable(solves) + "\n")
	b.WriteString("## LSQR\n\n" + LSQRTable(lsqr) + "\n## LSMR\n\n" + LSMRTable(lsmr) + "\n")
	b.WriteString("## Orderings (generated matrices, scrambled)\n\n" + OrderTable(orders) + "\n")
	if live != nil {
		b.WriteString("## Harwell-Boeing corpus (NIST Matrix Market, report only)\n\n")
		b.WriteString("Downloaded into a cache outside the repository (licence unstated), checked against pinned SHA-256 sums. Ill-conditioned matrices make Krylov iteration counts erratic, so nothing here is asserted.\n\n")
		b.WriteString(SolveTable(live.Solves) + "\n" + OrderTable(live.Orders) + "\n")
		for _, n := range live.Notes {
			b.WriteString("- " + n + "\n")
		}
	}
	return b.String()
}
